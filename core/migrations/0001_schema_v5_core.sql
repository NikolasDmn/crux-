-- Exam Board platform schema v5: CORE service database (2026-10-23)
-- Dialect: MySQL 8.0.16+. Loads clean on 8.0.46.
-- One MySQL server, one database per service: exam_core (this file), exam_files, exam_ai, exam_notify.
-- Owner: the Core service (Rust). No other service reads or writes these tables; they call Core's API.
-- History: schema-v4.sql + schema-v4-review.md; v5 changes listed in platform/backend-spec.md section 0.
--
-- Cross-service references
--   * A column ending in "Ref" (FileRef, RunRef, ...) holds the PublicId (CHAR(26) ULID) of a row in
--     ANOTHER service's database. No FK is possible; the owning service is asked over its API, and
--     "not found" must be handled (the other side may have deleted it).
--   * Other services refer to Core rows by Core's PublicId (UserRef, CourseRef, ...), never by Id.
--
-- Server / connection requirements
--   * database default: CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci
--     (case-insensitive: 'Nick' and 'nick' are the same username/email, which is what we want)
--   * default_time_zone = '+00:00' on the server AND on every pooled connection.
--     DEFAULT CURRENT_TIMESTAMP uses the session zone; without this, "UTC" columns silently aren't.
--   * sql_mode includes STRICT_TRANS_TABLES (MySQL 8 default) so bad ENUM values error instead of becoming ''.
--
-- Conventions
--   * Id: BIGINT AUTO_INCREMENT, internal only. Never put it in a URL or API response.
--   * PublicId: CHAR(26) ULID on every row the API addresses directly. Generated by the app,
--     sortable by time, not guessable (stops /mocks/41 -> /mocks/42 enumeration).
--   * ClientId: id generated on the device for rows that may be written offline or retried
--     (reviews, attempts, events). UNIQUE (UserId, ClientId) makes the write idempotent.
--   * RowVersion: optimistic concurrency on rows a user edits from two devices.
--     UPDATE ... SET ..., RowVersion = RowVersion + 1 WHERE Id = ? AND RowVersion = ?  (0 rows = conflict)
--   * UTC everywhere; DATETIME(3) where order within one second matters (answers, reviews, events).
--   * Soft delete (ArchivedAt / DeletedAt) for anything history points at; hard deletes only via
--     the account-deletion job, never ad hoc.
--   * ENUMs are append-only: add new values at the END (instant in MySQL 8), never reorder or remove.
--   * "App rule:" comments mark invariants MySQL cannot enforce; they need a service-layer check + a test.
--   * Every query on user data is scoped by the caller's UserId in the repository layer (MySQL has no
--     row-level security). Catalog reads go through the access check in schema-v4-review.md section 2.

