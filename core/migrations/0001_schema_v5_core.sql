-- 5. Questions (identity + immutable versions + typed keys)
-- =====================================================================
-- Question.Type is fixed for life and repeated on QuestionVersion and on the typed key table;
-- composite FKs make "an MC version with an Open key" impossible.
CREATE TABLE Question (
    Id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    PublicId          CHAR(26) NOT NULL,
    CourseId          BIGINT   NOT NULL,
    CourseComponentId BIGINT   NOT NULL,
    Type              ENUM('MC','Open','Numeric') NOT NULL,
    OwnerUserId       BIGINT   NULL,                     -- NULL = part of the course bank; set = private to one user
                                                         -- (AI questions generated from one user's weak spots start private)
    Source            ENUM('Generated','Lecture','Tutorial','PastExam','Practice','Manual','Imported','Unknown') NOT NULL,
    SourceLabel       VARCHAR(255) NULL,
    PaperId           BIGINT   NULL,
    PaperQuestionNo   VARCHAR(16) NULL,
    FamilyId          BIGINT   NULL,
    CurrentVersionId  BIGINT   NULL,                     -- FK added at the end (cycle)
    GeneratedByRunRef CHAR(26) NULL,                     -- AI service run
    SeedQuestionId    BIGINT   NULL,
    ReviewState       ENUM('Approved','Draft','Rejected') NOT NULL DEFAULT 'Approved',
    CreatedBy         BIGINT   NULL,
    CreatedAt         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    ArchivedAt        DATETIME NULL,
    RowVersion        INT      NOT NULL DEFAULT 0,
    UNIQUE KEY uq_question_public (PublicId),
    UNIQUE KEY uq_question_type (Id, Type),
    KEY idx_question_bank (CourseId, ArchivedAt, ReviewState, CourseComponentId),
    KEY idx_question_owner (OwnerUserId),
    KEY idx_question_paper (PaperId),
    KEY idx_question_family (FamilyId),
    FOREIGN KEY (CourseComponentId, CourseId) REFERENCES CourseComponent(Id, CourseId) ON DELETE RESTRICT,
    FOREIGN KEY (CourseId)         REFERENCES Course(Id)    ON DELETE RESTRICT,
    FOREIGN KEY (OwnerUserId)      REFERENCES Users(Id)     ON DELETE CASCADE,
    FOREIGN KEY (PaperId)          REFERENCES Paper(Id)     ON DELETE SET NULL,
    FOREIGN KEY (FamilyId)         REFERENCES Question(Id)  ON DELETE SET NULL,
    FOREIGN KEY (SeedQuestionId)   REFERENCES Question(Id)  ON DELETE SET NULL,
    FOREIGN KEY (CreatedBy)        REFERENCES Users(Id)     ON DELETE SET NULL
);
-- App rules: Paper and Family must be in the same course; PaperQuestionNo needs PaperId
-- (not a CHECK: PaperId is SET NULL on delete, error 3823); a Generated question's versions
-- may never have KeyReliability = 'Official'.

-- Versions are immutable: never UPDATE a row, insert VersionNo + 1 instead.
CREATE TABLE QuestionVersion (
    Id             BIGINT AUTO_INCREMENT PRIMARY KEY,
    QuestionId     BIGINT   NOT NULL,
    Type           ENUM('MC','Open','Numeric') NOT NULL,
    VersionNo      INT      NOT NULL,
    Prompt         TEXT     NOT NULL,
    ImageFileRef   CHAR(26) NULL,                        -- a cropped question image: Purpose 'QuestionImage', never purged
    Explanation    TEXT     NULL,
    KeyReliability ENUM('Official','Derived','Disputed') NOT NULL DEFAULT 'Derived',
    KeyNote        TEXT     NULL,
    ChangeNote     VARCHAR(255) NULL,
    EditedByRunRef CHAR(26) NULL,
    CreatedBy      BIGINT   NULL,
    CreatedAt      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_question_version (QuestionId, VersionNo),
    UNIQUE KEY uq_version_question (Id, QuestionId),     -- target: "this version belongs to this question"
    UNIQUE KEY uq_version_type (Id, Type),               -- target: "this key table matches the type"
    FOREIGN KEY (QuestionId, Type) REFERENCES Question(Id, Type) ON DELETE CASCADE,
    FOREIGN KEY (CreatedBy)     REFERENCES Users(Id)      ON DELETE SET NULL,
    CHECK (VersionNo >= 1)
);

