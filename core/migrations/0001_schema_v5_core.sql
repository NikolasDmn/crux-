CREATE TABLE ComponentMaterial (
    Id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    PublicId          CHAR(26)     NOT NULL,
    CourseComponentId BIGINT       NOT NULL,
    Kind              ENUM('Slides','Textbook','Exercise','PastExam','Notes','Other') NOT NULL,
    Title             VARCHAR(255) NOT NULL,
    Content           MEDIUMTEXT   NULL,                -- markdown body, or
    FileRef           CHAR(26)     NULL,                -- an uploaded file (Files service)
    FileSha256        CHAR(64)     NULL,                -- kept after the original is purged: a re-upload reattaches here
    OriginalStatus    ENUM('None','Present','PendingPurge','Purged') NOT NULL DEFAULT 'None',  -- storage saver
    OriginalPurgeAt   DATETIME     NULL,                -- PendingPurge: when the 7-day undo ends
    ContentFormat     VARCHAR(32)  NOT NULL DEFAULT 'markdown',
    PageFrom          INT          NULL,
    PageTo            INT          NULL,
    Excluded          BOOLEAN      NOT NULL DEFAULT FALSE,   -- lecturer: not for the exam
    ExcludedNote      VARCHAR(255) NULL,
    AiAllowed         BOOLEAN      NOT NULL DEFAULT TRUE,    -- owner can keep a file away from any model (licence, copyright)
    SortOrder         INT          NOT NULL DEFAULT 0,
    UpdatedAt         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    ArchivedAt        DATETIME     NULL,
    RowVersion        INT          NOT NULL DEFAULT 0,
    UNIQUE KEY uq_material_public (PublicId),
    KEY idx_material_component (CourseComponentId, SortOrder),
    FOREIGN KEY (CourseComponentId) REFERENCES CourseComponent(Id) ON DELETE CASCADE,
    KEY idx_material_sha (FileSha256),
    CHECK (Content IS NOT NULL OR FileRef IS NOT NULL OR FileSha256 IS NOT NULL),   -- a purged file keeps its fingerprint
    CHECK ((FileRef IS NULL) = (OriginalStatus = 'None')),
    CHECK ((OriginalStatus = 'PendingPurge') = (OriginalPurgeAt IS NOT NULL)),
    CHECK (PageFrom IS NULL OR PageFrom >= 1),
    CHECK (PageFrom IS NULL OR PageTo IS NULL OR PageTo >= PageFrom)
);

CREATE TABLE Paper (
