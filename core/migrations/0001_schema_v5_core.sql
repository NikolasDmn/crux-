-- =====================================================================
-- 14. Event log (append-only, the analytics source of truth)
-- =====================================================================
-- No foreign keys on purpose: (1) the log must survive catalog deletes, (2) MySQL can't partition
-- a table with FKs, and this is the table that will need monthly partitions first.
-- The account-deletion job deletes a user's events explicitly.
CREATE TABLE UserEvent (                                 -- 'Event' is a MySQL keyword; avoided
    Id          BIGINT AUTO_INCREMENT,
    UserId      BIGINT      NOT NULL,
    ActorUserId BIGINT      NULL,                        -- set when someone else (admin, course editor) acted
    ClientId    CHAR(26)    NULL,
    OccurredAt  DATETIME(3) NOT NULL,
    Type        VARCHAR(64) NOT NULL,                    -- 'mock.answer', 'flash.review', 'material.open', 'ai.ask'
    CourseId    BIGINT      NULL,
    ComponentId BIGINT      NULL,
    EntityType  VARCHAR(32) NULL,
    EntityId    BIGINT      NULL,
    Payload     JSON        NULL,
    PRIMARY KEY (Id, OccurredAt),                        -- partition key must be in every unique key
    KEY idx_event_user_time (UserId, OccurredAt),
    KEY idx_event_type (Type, OccurredAt),
    KEY idx_event_client (UserId, ClientId)              -- dedupe on ingest (can't be UNIQUE once partitioned)
);

-- =====================================================================
-- 15. Service messaging: transactional outbox + consumer dedupe (same two tables in every service DB)
-- =====================================================================
-- Write the domain change and the Outbox row in ONE transaction; a relay publishes unpublished rows
-- to the queue and sets PublishedAt. Consumers record EventId in ConsumedEvent in the same
-- transaction as their own change, so redelivery is harmless.
CREATE TABLE Outbox (
    Id           BIGINT AUTO_INCREMENT PRIMARY KEY,
    EventId      CHAR(26)    NOT NULL,                   -- ULID, global across services
    Topic        VARCHAR(64) NOT NULL,                   -- 'mock.submitted', 'material.purge_requested'
    SchemaVersion SMALLINT   NOT NULL DEFAULT 1,
    AggregateRef CHAR(26)    NULL,                       -- PublicId of the row it is about (ordering key)
    Payload      JSON        NOT NULL,
    CreatedAt    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PublishedAt  DATETIME(3) NULL,
    Attempts     INT         NOT NULL DEFAULT 0,
    UNIQUE KEY uq_outbox_event (EventId),
    KEY idx_outbox_pending (PublishedAt, Id)
);

CREATE TABLE ConsumedEvent (
    EventId    CHAR(26)    NOT NULL PRIMARY KEY,
    Topic      VARCHAR(64) NOT NULL,
    ConsumedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

