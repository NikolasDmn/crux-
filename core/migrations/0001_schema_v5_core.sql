-- Grade scales vary per course (Nick 2026-10-23): Dutch 1-10, percent, letters, pass/fail.
-- Built-in scales have OwnerUserId NULL; users can define their own.
CREATE TABLE GradeScale (
    Id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    OwnerUserId   BIGINT       NULL,
    Name          VARCHAR(64)  NOT NULL,                 -- 'NL 1-10', 'Percent', 'US letter', 'Pass/Fail'
    Kind          ENUM('Numeric','Letter','PassFail') NOT NULL,
    ScaleMin      DECIMAL(6,2) NULL,                     -- Numeric: 1.00
    ScaleMax      DECIMAL(6,2) NULL,                     -- Numeric: 10.00
    Step          DECIMAL(6,2) NULL,                     -- 0.1
    PassValue     DECIMAL(6,2) NULL,                     -- 5.5
    Labels        JSON         NULL,                     -- Letter: [{"label":"A","value":4.0,"pass":true}, ...]
    FOREIGN KEY (OwnerUserId) REFERENCES Users(Id) ON DELETE CASCADE,
    CHECK (Kind <> 'Numeric' OR (ScaleMin IS NOT NULL AND ScaleMax IS NOT NULL AND ScaleMax > ScaleMin)),
    CHECK (Kind <> 'Letter' OR Labels IS NOT NULL)
);
