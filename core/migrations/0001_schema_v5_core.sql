-- Membership tiers. Every limit is a column (or Limits JSON while it is still moving), never a
-- constant in code, so a paid plan later is a new row. Billing tables come with payments.
CREATE TABLE Tier (
    Id                BIGINT AUTO_INCREMENT PRIMARY KEY,
    Code              VARCHAR(32)  NOT NULL,              -- 'free', 'plus'
    Name              VARCHAR(64)  NOT NULL,
    StorageQuotaBytes BIGINT       NOT NULL,              -- free: 1 GiB = 1073741824
    MaxCourses        INT          NULL,                  -- NULL = unlimited
    Limits            JSON         NULL,                  -- future limits, e.g. {"maxImportMb":500}
    IsDefault         BOOLEAN      NOT NULL DEFAULT FALSE, -- the tier new users get; exactly one (app rule)
    IsActive          BOOLEAN      NOT NULL DEFAULT TRUE,  -- retired tiers stay for users already on them
    SortOrder         INT          NOT NULL DEFAULT 0,
    UNIQUE KEY uq_tier_code (Code),
    CHECK (StorageQuotaBytes >= 0)
);
INSERT INTO Tier (Code, Name, StorageQuotaBytes, IsDefault, SortOrder) VALUES ('free', 'Free', 1073741824, TRUE, 0);

CREATE TABLE Users (
    Id              BIGINT AUTO_INCREMENT PRIMARY KEY,
    PublicId        CHAR(26)     NOT NULL,
    Username        VARCHAR(32)  NOT NULL,
    Email           VARCHAR(255) NOT NULL,
    EmailVerifiedAt DATETIME     NULL,
    PasswordHash    VARCHAR(255) NULL,                  -- NULL for SSO-only accounts; argon2id string
    FirstName       VARCHAR(255) NOT NULL,
    LastName        VARCHAR(255) NOT NULL,
    TimeZone        VARCHAR(64)  NOT NULL DEFAULT 'Europe/Amsterdam',
    Locale          VARCHAR(16)  NOT NULL DEFAULT 'en',
    Role            ENUM('User','Admin') NOT NULL DEFAULT 'User',
    TierId          BIGINT       NOT NULL,              -- membership tier (storage quota, later paid limits)
    Status          ENUM('Active','Disabled','PendingDeletion') NOT NULL DEFAULT 'Active',
    CreatedAt       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DeletionRequestedAt DATETIME NULL,                  -- grace period before the deletion job runs
    RowVersion      INT          NOT NULL DEFAULT 0,
    UNIQUE KEY uq_user_public (PublicId),
    UNIQUE KEY uq_user_username (Username),
    UNIQUE KEY uq_user_email (Email),
    FOREIGN KEY (TierId) REFERENCES Tier(Id) ON DELETE RESTRICT
);

-- Every tier change, with who/why. Payments will reference this later.
CREATE TABLE UserTierChange (
    Id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    UserId     BIGINT       NOT NULL,
    FromTierId BIGINT       NULL,
    ToTierId   BIGINT       NOT NULL,
    ChangedAt  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ChangedBy  BIGINT       NULL,                        -- admin; NULL = system
    Reason     VARCHAR(255) NULL,                        -- 'signup', 'invite bonus', 'payment'
    KEY idx_tierchange_user (UserId, ChangedAt),
    FOREIGN KEY (UserId)     REFERENCES Users(Id) ON DELETE CASCADE,
    FOREIGN KEY (FromTierId) REFERENCES Tier(Id)  ON DELETE RESTRICT,
    FOREIGN KEY (ToTierId)   REFERENCES Tier(Id)  ON DELETE RESTRICT,
    FOREIGN KEY (ChangedBy)  REFERENCES Users(Id) ON DELETE SET NULL
);

-- Invite-only signup (Nick 2026-10-23).
CREATE TABLE Invite (
    Id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    CodeHash    CHAR(64)     NOT NULL,                   -- sha256 of the invite code
    Email       VARCHAR(255) NULL,                       -- set = only this address can use it
    InvitedBy   BIGINT       NULL,
    TierId      BIGINT       NULL,                       -- NULL = default tier
    MaxUses     INT          NOT NULL DEFAULT 1,
    Uses        INT          NOT NULL DEFAULT 0,
    ExpiresAt   DATETIME     NULL,
    CreatedAt   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RevokedAt   DATETIME     NULL,
    UNIQUE KEY uq_invite_code (CodeHash),
    FOREIGN KEY (InvitedBy) REFERENCES Users(Id) ON DELETE SET NULL,
    FOREIGN KEY (TierId)    REFERENCES Tier(Id)  ON DELETE RESTRICT,
    CHECK (Uses >= 0 AND Uses <= MaxUses)
);

CREATE TABLE UserIdentity (                             -- SSO / OAuth logins (university SSO, Google, ...)
