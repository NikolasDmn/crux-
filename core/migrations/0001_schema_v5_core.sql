-- Every course has exactly one owner (a platform-curated course is owned by an admin account).
-- Sharing = CourseMember (edit/view the same catalog) or a fork (OriginCourseId = copy you own).
CREATE TABLE Course (
    Id             BIGINT AUTO_INCREMENT PRIMARY KEY,
    PublicId       CHAR(26)     NOT NULL,
    OwnerUserId    BIGINT       NOT NULL,
    Name           VARCHAR(255) NOT NULL,
    Code           VARCHAR(16)  NOT NULL,               -- 'BSA'; unique per owner
    Institution    VARCHAR(255) NULL,
    Term           VARCHAR(32)  NULL,                   -- '2026-27 Q1'
    Locale         VARCHAR(16)  NOT NULL DEFAULT 'en',
    Visibility     ENUM('Private','Shared','Public') NOT NULL DEFAULT 'Private',
    OriginCourseId BIGINT       NULL,                   -- forked from
    Color          CHAR(7)      NOT NULL DEFAULT '#38bdf8',  -- one colour per course; owner/Editors change it
    GradeScaleId   BIGINT       NOT NULL,
    CreatedAt      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    ArchivedAt     DATETIME     NULL,
    RowVersion     INT          NOT NULL DEFAULT 0,
    UNIQUE KEY uq_course_public (PublicId),
    UNIQUE KEY uq_course_owner_code (OwnerUserId, Code),
    FOREIGN KEY (OwnerUserId)    REFERENCES Users(Id)  ON DELETE RESTRICT,   -- deletion job transfers or removes first
    FOREIGN KEY (OriginCourseId) REFERENCES Course(Id) ON DELETE SET NULL,
    FOREIGN KEY (GradeScaleId)   REFERENCES GradeScale(Id) ON DELETE RESTRICT,
    CHECK (Color REGEXP '^#[0-9a-fA-F]{6}$')
);

