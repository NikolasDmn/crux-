CREATE TABLE CourseComponent (                          -- a lecture / block / tutorial
    Id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    PublicId    CHAR(26)     NOT NULL,
    CourseId    BIGINT       NOT NULL,
    Code        VARCHAR(8)   NOT NULL,                  -- 'L6', 'B3'
